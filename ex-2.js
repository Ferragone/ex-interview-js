/*2. Анаграма (Робота з рядками)

Умова: Напишіть функцію, яка приймає два рядки і визначає, чи є вони 
анаграмами один одного (чи складаються з однакових літер у різній послідовності). 
Пробіли, розділові знаки та регістр літер не повинні враховуватися (наприклад, "А роза упала на 
лапу Азора" та "Азор, лапа, упала, роза, на, а" — анаграми).
Що перевіряє: Роботу з регулярними виразами (RegEx) для очищення рядка, методи масивів
(split, sort, join) або створення словника частот (через об'єкт чи Map) для оптимізованого
порівняння.*/

function isAnagram(str1, str2) {
  // Допоміжна функція для очищення та сортування
  const normalize = (str) => {
    return str
      .replace(/[^\wа-яА-ЯіІїЇєЄґҐ]/g, '') // Видаляємо пробіли та знаки
      .toLowerCase()                        // Зводимо до нижнього регістру
      .split('')                            // Перетворюємо на масив літер
      .sort()                               // Сортуємо за алфавітом
      .join('');                            // Збираємо назад у рядок
  };

  return normalize(str1) === normalize(str2);
}

console.log(isAnagram("А роза упала на лапу Азора", "Азор, лапа, упала, роза, на, а")); // true